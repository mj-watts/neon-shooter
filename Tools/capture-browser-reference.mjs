import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const project=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const require=createRequire(path.join(project,'../browser-neon-shooter/package.json'));
const {chromium}=require('@playwright/test');
const output=path.join(project,'TestResults/VisualParity');
const browser=await chromium.launch({headless:true,args:['--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1280,height:800},reducedMotion:'reduce'});
await page.goto('http://127.0.0.1:5173');
await page.locator('.terms-launch-copy').scrollIntoViewIfNeeded();
await page.screenshot({path:output+'/browser-launch.png'});
await page.getByRole('button',{name:'Launch flight'}).click();
await page.locator('.flight-wave strong').filter({hasText:'01'}).waitFor({timeout:15000});
console.log(await page.evaluate(()=>performance.getEntriesByType('resource').filter(e=>e.name.includes('NeonShooter')).map(e=>e.name)));
await page.evaluate(async()=>{for(const path of performance.getEntriesByType('resource').filter(e=>e.name.includes('NeonShooter')).map(e=>e.name)){const{default:Game}=await import(path);const animate=Game.prototype.animate;Game.prototype.animate=function(...args){window.referenceGame=this;return animate.apply(this,args)}}});
await page.waitForFunction(()=>window.referenceGame?.model);
await page.evaluate(()=>{const g=referenceGame;g.reducedMotion=false;g.model.startWave();g.model.player.invulnerable=100;g.model.paused=true;g.model.enemies=[];g.model.bullets=[];g.particles=[];g.rings=[];g.syncEntities(0);g.composer.render();});
await page.getByRole('button',{name:'Resume',exact:true}).waitFor();
await page.screenshot({path:output+'/browser-paused.png'});
await page.evaluate(()=>{const g=referenceGame;cancelAnimationFrame(g.frame);g.model.paused=false;g.publish();g.composer.render();});
await page.screenshot({path:output+'/browser-flight.png'});
await page.evaluate(()=>{const g=referenceGame;for(const [x,y,color] of [[-9,3,'pink'],[5,7,'cyan'],[10,-3,'gold']])g.burst(x,y,1.5,color,true);for(let i=0;i<24;i++)g.updateParticles(1/60);g.composer.render();});
await page.screenshot({path:output+'/browser-explosions.png'});
console.log('Captured browser launch, pause, flight and explosions.');
await page.evaluate(()=>{const g=referenceGame;g.model.phase='gameover';g.publish();});
await page.screenshot({path:output+'/browser-gameover.png'});
await browser.close();
